"""Cohérence de la spec protocole (#90) avec le moteur et le code.

- la référence des pièces est **générée** et ne doit pas diverger du modèle ;
- les énumérations du schéma JSON doivent correspondre aux tables de `naming` ;
- la doc doit embarquer les blocs générés.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

from orapa_mine.model import gems_catalog as cat
from orapa_mine.solver import naming
from orapa_mine.solver.session import (
    IllegalMove,
    IncompleteBoard,
    SessionFinished,
    UnknownPiece,
)

_ROOT = Path(__file__).resolve().parents[1]
_DOC = _ROOT / "docs" / "HACKATHON_PROTOCOL.md"
_SCHEMA = _ROOT / "schema" / "hackathon_protocol.schema.json"


def _load_piece_reference():
    spec = importlib.util.spec_from_file_location(
        "piece_reference", _ROOT / "tools" / "piece_reference.py"
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("piece_reference", module)
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module


# --- Référence générée : fidèle au modèle ------------------------------------


def test_pieces_markdown_lists_every_piece_with_its_orientation_count():
    md = _load_piece_reference().pieces_markdown()
    for piece in cat.ALL_PIECES.values():
        wire = naming.piece_id(piece.name)
        assert f"`{wire}`" in md
        # Une ligne « orient N » par orientation réelle de la pièce.
        n = len(piece.orientations())
        for idx in range(n):
            assert f"**orient {idx}**" in md


def test_colors_markdown_has_all_fifteen_mixes():
    md = _load_piece_reference().colors_markdown()
    # 15 combinaisons de la table de mélange, toutes en tokens ASCII.
    assert md.count("|") >= 15 * 2
    for token in ("orange", "green", "purple", "gray", "light-blue"):
        assert f"`{token}`" in md


# --- Schéma JSON : énumérations alignées sur le code -------------------------


def _schema() -> dict:
    return json.loads(_SCHEMA.read_text(encoding="utf-8"))


def test_schema_is_valid_json_with_message_defs():
    defs = _schema()["$defs"]
    for msg in ("hello", "shoot", "shot", "query", "cell", "place", "remove",
                "ack", "reject", "submit", "result", "give_up", "end", "inventory", "pieces"):
        assert msg in defs


def test_schema_piece_ids_match_naming():
    defs = _schema()["$defs"]
    assert set(defs["pieceId"]["enum"]) == set(naming.PIECE_ID_TO_NAME)
    assert set(defs["gemColor"]["enum"]) == set(naming.COLOR_TO_ASCII.values())
    assert set(defs["rayColor"]["enum"]) == set(naming.RAY_COLOR_TO_ASCII.values())
    assert set(defs["extensionKind"]["enum"]) == set(naming.EXTENSION_KIND_TO_ASCII.values())


def test_schema_reject_reasons_match_session_errors():
    reasons = set(_schema()["$defs"]["reject"]["properties"]["reason"]["enum"])
    expected = {e.reason for e in (UnknownPiece, IllegalMove, IncompleteBoard, SessionFinished)}
    assert reasons == expected


# --- La doc embarque bien les blocs générés ----------------------------------


def test_doc_embeds_generated_reference():
    text = _DOC.read_text(encoding="utf-8")
    assert "GENERATED by tools/piece_reference.py" in text
    assert "Appendix A — Pieces & orientations" in text
    assert "Appendix B — Ray colours" in text
    for wire in naming.PIECE_ID_TO_NAME:
        assert f"`{wire}`" in text
