"""Génère la référence « pièces / ancre / orientations » du protocole (#90).

Sortie Markdown dérivée **du modèle** (`gems_catalog` + `Piece.orientations()`)
pour que la documentation ne puisse jamais diverger du moteur. On y lit, pour
chaque pièce : son identifiant fil (ASCII), sa géométrie d'orientation 0 et de
toutes ses rotations/retournements, l'ancre, et un exemple de `place`.

Usage :
    uv run --no-sync python tools/piece_reference.py            # pièces + couleurs
    uv run --no-sync python tools/piece_reference.py --pieces   # pièces seules
    uv run --no-sync python tools/piece_reference.py --colors   # couleurs seules

Lancé sans I/O graphique (aucun pygame).
"""

from __future__ import annotations

import sys

from orapa_mine.model import gems_catalog as cat
from orapa_mine.model.beam import COLOR_MIX_TABLE
from orapa_mine.model.gems import GemColor, HalfCell, Piece, Position
from orapa_mine.solver import naming

# Glyphes des demi-cases : plein, et triangles rectangles (coin de l'angle droit).
_GLYPH: dict[str, str] = {
    HalfCell.FULL.value: "█",
    HalfCell.RA_NW.value: "◤",
    HalfCell.RA_NE.value: "◥",
    HalfCell.RA_SW.value: "◣",
    HalfCell.RA_SE.value: "◢",
}
_EMPTY = "·"

# Ordre d'affichage stable (par identifiant fil).
_PIECES: list[Piece] = sorted(cat.ALL_PIECES.values(), key=lambda p: naming.piece_id(p.name))


def _render(footprint: frozenset[tuple[Position, HalfCell]]) -> list[str]:
    """Dessine une empreinte (ancrée en (0,0)) en lignes ASCII."""
    grid = {(p.row, p.col): _GLYPH[hc.value] for p, hc in footprint}
    max_row = max(r for r, _ in grid)
    max_col = max(c for _, c in grid)
    return [
        "".join(grid.get((r, c), _EMPTY) for c in range(max_col + 1))
        for r in range(max_row + 1)
    ]


def _cells_list(footprint: frozenset[tuple[Position, HalfCell]]) -> str:
    cells = sorted((p.row, p.col, hc.value) for p, hc in footprint)
    return ", ".join(f"({r},{c}) {hc}" for r, c, hc in cells)


def pieces_markdown() -> str:
    lines: list[str] = []
    lines.append("<!-- GENERATED by tools/piece_reference.py — do not edit by hand -->")
    lines.append("")
    lines.append(
        "Glyphs: `█` full cell · `◤ ◥ ◣ ◢` right-triangle half-cells (filled corner) · "
        "`·` empty. The **anchor** is the top-left cell `(0,0)` of the bounding box; "
        "`orient` is the index below (0 = canonical)."
    )
    for piece in _PIECES:
        wire = naming.piece_id(piece.name)
        orients = piece.orientations()
        mystery = " · colour is the solver's **guess** (`color` required)" if wire == "mystery" else ""
        lines.append("")
        lines.append(f"### `{piece.name}` → wire id **`{wire}`** ({len(orients)} orientation(s)){mystery}")
        for idx, footprint in enumerate(orients):
            art = _render(footprint)
            lines.append("")
            lines.append(f"- **orient {idx}** — cells: {_cells_list(footprint)}")
            lines.append("  ```")
            for row in art:
                lines.append(f"  {row}")
            lines.append("  ```")
        color = ', color:"red"' if wire == "mystery" else ""
        lines.append("")
        lines.append(
            f"  Example: `{{\"type\":\"place\",\"piece\":\"{wire}\","
            f"\"anchor\":{{\"row\":3,\"col\":4}},\"orient\":0{color}}}`"
        )
    return "\n".join(lines)


def colors_markdown() -> str:
    """Table de mélange des rayons, en tokens ASCII (dérivée du moteur)."""
    order = [GemColor.RED, GemColor.YELLOW, GemColor.BLUE, GemColor.WHITE]
    lines: list[str] = []
    lines.append("<!-- GENERATED by tools/piece_reference.py — do not edit by hand -->")
    lines.append("")
    lines.append("Base gem colours (wire tokens): `red`, `yellow`, `blue`, `white`.")
    lines.append("")
    lines.append("A ray's announced colour is the mix of the distinct gem colours it touched "
                 "(`null` if it touched none). Full table (wire tokens):")
    lines.append("")
    lines.append("| Gem colours touched | Ray colour |")
    lines.append("|---------------------|------------|")
    # Tri par nombre de couleurs puis par ordre canonique, pour une table stable.
    def key(item):
        combo = item[0]
        return (len(combo), tuple(order.index(c) for c in order if c in combo))
    for combo, french in sorted(COLOR_MIX_TABLE.items(), key=key):
        ins = " + ".join(naming.color_to_ascii(c) for c in order if c in combo)
        out = naming.ray_color_to_ascii(french)
        lines.append(f"| {ins} | `{out}` |")
    return "\n".join(lines)


def main(argv: list[str]) -> None:
    # Les glyphes (█ ◤ …) sont de l'UTF-8 ; forcer l'encodage sous Windows (cp1252).
    try:
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
    except (AttributeError, ValueError):
        pass
    want_pieces = "--colors" not in argv
    want_colors = "--pieces" not in argv
    blocks: list[str] = []
    if want_pieces:
        blocks.append(pieces_markdown())
    if want_colors:
        blocks.append(colors_markdown())
    print("\n\n".join(blocks))


if __name__ == "__main__":
    main(sys.argv[1:])
